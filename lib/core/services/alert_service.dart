import 'dart:convert';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';
import '../models/alert_model.dart';
import 'safety_engine.dart';
import 'local_database_service.dart';
import 'sync_service.dart';

class AlertService {
  static final AlertService _instance = AlertService._internal();
  factory AlertService({LocalDatabaseService? localDb}) {
    if (localDb != null) _instance._localDb = localDb;
    return _instance;
  }
  AlertService._internal();

  final FirebaseFirestore _firestore = FirebaseFirestore.instance;
  final FirebaseAuth _auth = FirebaseAuth.instance;
  LocalDatabaseService _localDb = LocalDatabaseService();

  String? get currentUid => _auth.currentUser?.uid;

  CollectionReference<Map<String, dynamic>> _userAlertsRef(String uid) {
    return _firestore.collection('users').doc(uid).collection('alerts');
  }

  /// Real-time stream of alerts for the current authenticated user ordered by timestamp descending
  Stream<List<AlertModel>> getAlertsStream() {
    final uid = currentUid;
    if (uid == null) {
      return Stream.value([]);
    }

    return _userAlertsRef(uid)
        .orderBy('timestamp', descending: true)
        .snapshots()
        .map((snapshot) {
      return snapshot.docs.map((doc) => AlertModel.fromFirestore(doc)).toList();
    });
  }

  /// Fetch alerts with offline fallback and background synchronization
  Future<List<AlertModel>> getAlerts() async {
    final uid = currentUid;
    if (uid == null) return [];

    // Attempt background sync of unsynced offline alerts
    syncOfflineAlerts().catchError((e) {
      debugPrint('Sync offline alerts failed in background: $e');
    });

    List<AlertModel> cloudAlerts = [];
    try {
      final querySnapshot = await _userAlertsRef(uid)
          .orderBy('timestamp', descending: true)
          .get(const GetOptions(source: Source.serverAndCache))
          .timeout(const Duration(seconds: 8));

      cloudAlerts = querySnapshot.docs
          .map((doc) => AlertModel.fromFirestore(doc))
          .toList();

      if (cloudAlerts.isNotEmpty) {
        for (final a in cloudAlerts) {
          try {
            await _localDb.insertAlert(a, uid: uid);
          } catch (_) {}
        }
        await _cacheAlertsLocally(uid, cloudAlerts);
      }
    } catch (e) {
      debugPrint('Firestore getAlerts failed: $e');
    }

    // Always fetch all local SQLite alerts to ensure offline/unsynced alerts show up
    List<AlertModel> localAlerts = [];
    try {
      localAlerts = await _localDb.getAlerts(uid: uid);
    } catch (e) {
      debugPrint('SQLite getAlerts failed: $e');
    }

    if (localAlerts.isEmpty) {
      localAlerts = await _getLocalAlerts(uid);
    }

    final Map<String, AlertModel> mergedMap = {};
    for (final a in cloudAlerts) {
      mergedMap[a.id] = a;
    }
    for (final a in localAlerts) {
      if (!mergedMap.containsKey(a.id) || !a.isSynced) {
        mergedMap[a.id] = a;
      }
    }

    final result = mergedMap.values.toList();
    result.sort((a, b) => b.timestamp.compareTo(a.timestamp));
    return result;
  }

  /// Save valid safety alert generated by SafetyEngine to Cloud Firestore and local store
  Future<AlertModel?> saveSafetyAlert({
    required SafetyStatus status,
    String? tripId,
    double? latitude,
    double? longitude,
    double? distanceMeters,
    double? relativeSpeedKmh,
  }) async {
    // Only persist actionable safety events (caution, warning, critical)
    if (status.riskLevel != RiskLevel.caution &&
        status.riskLevel != RiskLevel.warning &&
        status.riskLevel != RiskLevel.critical) {
      return null;
    }

    final uid = currentUid;
    if (uid == null) {
      debugPrint('No authenticated user. Alert not persisted.');
      return null;
    }

    final docRef = _userAlertsRef(uid).doc();
    final alertId = docRef.id;
    final now = DateTime.now();

    final severityStr = status.riskLevel.toString().split('.').last.toLowerCase();
    final alertType = status.riskLevel == RiskLevel.critical
        ? 'CRITICAL_COLLISION_ALERT'
        : (status.riskLevel == RiskLevel.warning
            ? 'COLLISION_WARNING'
            : 'CAUTION_ALERT');

    final alert = AlertModel(
      id: alertId,
      tripId: tripId,
      alertType: alertType,
      severity: severityStr,
      message: status.message,
      source: 'SafetyEngine',
      distance: distanceMeters,
      relativeSpeed: relativeSpeedKmh,
      ttc: status.ttcSeconds,
      latitude: latitude,
      longitude: longitude,
      timestamp: now,
      createdAt: now,
      isSynced: false,
    );

    // 1. Save to SQLite local database first (and queue for sync)
    try {
      await _localDb.insertAlert(alert, uid: uid);
    } catch (e) {
      debugPrint('SQLite insertAlert failed: $e');
    }
    // Backup to SharedPreferences
    await _saveAlertLocally(uid, alert);

    // 2. Save asynchronously to Cloud Firestore without blocking safety operations
    _uploadAlertToCloud(uid, docRef, alert);

    return alert;
  }

  Future<void> _uploadAlertToCloud(
    String uid,
    DocumentReference<Map<String, dynamic>> docRef,
    AlertModel alert,
  ) async {
    try {
      await docRef.set(alert.toFirestoreMap(useServerTimestamp: true));
      final syncedAlert = alert.copyWith(isSynced: true);
      try {
        await _localDb.updateAlertSyncStatus(alert.id, isSynced: true);
      } catch (_) {}
      await _updateLocalAlert(uid, syncedAlert);
      debugPrint('Alert ${alert.id} successfully saved to Cloud Firestore.');
    } catch (e) {
      debugPrint('Cloud save failed for alert ${alert.id}: $e. Preserved locally.');
      try {
        await _localDb.updateAlertSyncStatus(alert.id, isSynced: false, syncError: e.toString());
      } catch (_) {}
    }
  }

  /// Sync all locally stored alerts with isSynced == false
  Future<void> syncOfflineAlerts() async {
    final uid = currentUid;
    if (uid == null) return;

    // Delegate to unified SyncService
    try {
      await SyncService().syncAll(uid: uid);
    } catch (e) {
      debugPrint('SyncService.syncAll failed for alerts: $e');
    }

    // Secondary fallback sync for SharedPreferences if any legacy alerts remain
    final localAlerts = await _getLocalAlerts(uid);
    final unsyncedAlerts = localAlerts.where((a) => !a.isSynced).toList();

    if (unsyncedAlerts.isEmpty) return;
    debugPrint('Found ${unsyncedAlerts.length} legacy unsynced alerts. Synchronizing...');

    for (final alert in unsyncedAlerts) {
      try {
        final docRef = _userAlertsRef(uid).doc(alert.id);
        await docRef.set(alert.toFirestoreMap(useServerTimestamp: false), SetOptions(merge: true));
        final synced = alert.copyWith(isSynced: true);
        await _updateLocalAlert(uid, synced);
        try {
          await _localDb.updateAlertSyncStatus(alert.id, isSynced: true);
        } catch (_) {}
        debugPrint('Successfully synchronized offline alert ${alert.id}');
      } catch (e) {
        debugPrint('Failed to sync alert ${alert.id}: $e');
      }
    }
  }

  /// Clear all alerts both locally and in Cloud Firestore
  Future<void> clearAllAlerts() async {
    final uid = currentUid;
    if (uid == null) return;

    // Clear SQLite local database
    try {
      await _localDb.clearAllAlerts(uid: uid);
    } catch (e) {
      debugPrint('Failed to clear SQLite alerts: $e');
    }

    final prefs = await SharedPreferences.getInstance();
    await prefs.remove('neurodrive_alerts_$uid');

    try {
      final snapshot = await _userAlertsRef(uid).get();
      final batch = _firestore.batch();
      for (final doc in snapshot.docs) {
        batch.delete(doc.reference);
      }
      await batch.commit();
      debugPrint('All Firestore alerts cleared for $uid');
    } catch (e) {
      debugPrint('Failed to clear Firestore alerts: $e');
    }
  }

  /// Save directly provided AlertModel (used for verified test mock generation)
  Future<void> saveDirectAlert(AlertModel alert) async {
    final uid = currentUid;
    if (uid == null) return;

    try {
      await _localDb.insertAlert(alert, uid: uid);
    } catch (_) {}
    await _saveAlertLocally(uid, alert);

    final docRef = _userAlertsRef(uid).doc(alert.id);
    _uploadAlertToCloud(uid, docRef, alert);
  }

  // --- Local SharedPreferences Helpers ---

  Future<List<AlertModel>> _getLocalAlerts(String uid) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final alertsStr = prefs.getStringList('neurodrive_alerts_$uid') ?? [];
      final alerts = alertsStr.map((a) {
        final map = json.decode(a) as Map<String, dynamic>;
        return AlertModel.fromMap(map);
      }).toList();
      alerts.sort((a, b) => b.timestamp.compareTo(a.timestamp));
      return alerts;
    } catch (e) {
      debugPrint('Failed to load local alerts: $e');
      return [];
    }
  }

  Future<void> _saveAlertLocally(String uid, AlertModel alert) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final alertsStr = prefs.getStringList('neurodrive_alerts_$uid') ?? [];

      final exists = alertsStr.any((a) {
        final map = json.decode(a) as Map<String, dynamic>;
        return (map['id'] ?? map['alertId']) == alert.id;
      });

      if (!exists) {
        alertsStr.add(json.encode(alert.toJsonMap()));
        await prefs.setStringList('neurodrive_alerts_$uid', alertsStr);
      }
    } catch (e) {
      debugPrint('Failed to write local alert: $e');
    }
  }

  Future<void> _updateLocalAlert(String uid, AlertModel alert) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final alertsStr = prefs.getStringList('neurodrive_alerts_$uid') ?? [];
      final updatedList = <String>[];

      for (final a in alertsStr) {
        final map = json.decode(a) as Map<String, dynamic>;
        if ((map['id'] ?? map['alertId']) == alert.id) {
          updatedList.add(json.encode(alert.toJsonMap()));
        } else {
          updatedList.add(a);
        }
      }

      await prefs.setStringList('neurodrive_alerts_$uid', updatedList);
    } catch (e) {
      debugPrint('Failed to update local alert: $e');
    }
  }

  Future<void> _cacheAlertsLocally(String uid, List<AlertModel> cloudAlerts) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final existingLocal = await _getLocalAlerts(uid);
      final unsynced = existingLocal.where((a) => !a.isSynced).toList();

      final merged = <String, AlertModel>{};
      for (final a in cloudAlerts) {
        merged[a.id] = a;
      }
      for (final a in unsynced) {
        merged[a.id] = a;
      }

      final resultList = merged.values.toList();
      resultList.sort((a, b) => b.timestamp.compareTo(a.timestamp));

      final serialized = resultList.map((a) => json.encode(a.toJsonMap())).toList();
      await prefs.setStringList('neurodrive_alerts_$uid', serialized);
    } catch (e) {
      debugPrint('Failed to cache alerts locally: $e');
    }
  }
}
